import { useMemo, useState } from 'react'
import { Bar, BarChart, CartesianGrid, Cell, Legend, Pie, PieChart, ResponsiveContainer, Tooltip, XAxis, YAxis } from 'recharts'
import { Card, Empty, Kpi, Select } from '../components/ui'
import { Agg, METRICS, Profile, Row, aggregate, fmt, insights, kpis, limitations } from '../lib/data'
const COLORS = ['#4f46e5', '#0ea5e9', '#14b8a6', '#8b5cf6', '#f59e0b', '#ec4899', '#64748b']

export function DimView({ rows, p, options, metric0 = 'convRate', title }: { rows: Row[]; p: Profile; options: string[][]; metric0?: string; title: string }) {
  const opts = options.filter(o => o.every(c => p.columns.includes(c)))
  const [oi, setOi] = useState(0), [m, setM] = useState(metric0), [desc, setDesc] = useState(true)
  const M = METRICS.find(x => x.key === m)!
  const data = useMemo(() => {
    if (!opts[oi]) return [] as Agg[]
    return aggregate(rows, p, opts[oi]).sort((a, b) => ((b[m] ?? -Infinity) - (a[m] ?? -Infinity)) * (desc ? 1 : -1))
  }, [rows, p, oi, m, desc])
  if (!opts.length) return <Empty text={`${title}: the required columns (${options.flat().join(', ')}) are not in this dataset.`} />
  if (!rows.length) return <Empty text="No records match the current filters." />
  const valid = data.filter(d => d[m] !== null)
  return (
    <Card title={title} right={<div className="flex gap-2 flex-wrap">
      {opts.length > 1 && <Select aria-label="Group by" value={oi} onChange={e => setOi(+e.target.value)}>{opts.map((o, i) => <option key={i} value={i}>By {o.join(' × ')}</option>)}</Select>}
      <Select aria-label="Metric" value={m} onChange={e => setM(e.target.value)}>{METRICS.map(x => <option key={x.key} value={x.key}>{x.label}</option>)}</Select>
      <button className="text-sm border rounded-lg px-2 py-1" onClick={() => setDesc(!desc)}>{desc ? 'High → Low' : 'Low → High'}</button></div>}>
      <div className="grid lg:grid-cols-3 gap-4">
        <div className="lg:col-span-2 h-72"><ResponsiveContainer><BarChart data={valid}><CartesianGrid strokeDasharray="3 3" />
          <XAxis dataKey="name" tick={{ fontSize: 11 }} interval={0} angle={valid.length > 5 ? -30 : 0} textAnchor={valid.length > 5 ? 'end' : 'middle'} height={valid.length > 5 ? 70 : 30} />
          <YAxis tick={{ fontSize: 11 }} tickFormatter={v => fmt(v, M.fmt)} label={{ value: M.label, angle: -90, position: 'insideLeft', fontSize: 11 }} />
          <Tooltip formatter={(v: any) => fmt(v, M.fmt)} /><Bar dataKey={m} name={M.label} fill="#4f46e5" radius={[6, 6, 0, 0]} /></BarChart></ResponsiveContainer></div>
        <div className="h-72"><ResponsiveContainer><PieChart><Pie data={data.filter(d => d.spend > 0)} dataKey="spend" nameKey="name" innerRadius="55%" outerRadius="80%">
          {data.map((_, i) => <Cell key={i} fill={COLORS[i % COLORS.length]} />)}</Pie><Tooltip formatter={(v: any) => fmt(v, 'money')} /><Legend wrapperStyle={{ fontSize: 11 }} /></PieChart></ResponsiveContainer>
          <p className="text-xs text-center text-slate-500 -mt-2">Ad spend contribution</p></div>
      </div>
      {valid.length > 1 && <p className="text-sm mt-3 text-slate-600">Highest {M.label}: <b>{valid.reduce((a, b) => (b[m] > a[m] ? b : a)).name}</b> · Lowest: <b>{valid.reduce((a, b) => (b[m] < a[m] ? b : a)).name}</b> (observed values, selected metric only).</p>}
      <div className="overflow-x-auto mt-3"><table className="w-full text-sm"><thead><tr className="text-left text-slate-500 border-b">
        <th className="py-1 pr-3">Group</th>{METRICS.map(x => <th key={x.key} className="px-2 whitespace-nowrap">{x.label}</th>)}</tr></thead>
        <tbody>{data.map(d => <tr key={d.name} className="border-b last:border-0"><td className="py-1 pr-3 font-medium">{d.name}</td>
          {METRICS.map(x => <td key={x.key} className="px-2 tabular-nums">{fmt(d[x.key], x.fmt)}</td>)}</tr>)}</tbody></table></div>
    </Card>)
}

export function Overview({ rows, p }: { rows: Row[]; p: Profile }) {
  const k = kpis(rows, p)
  return <div className="space-y-4">
    {rows.length ? <div className="grid grid-cols-2 xl:grid-cols-4 gap-3">{k.map(x => <Kpi key={x.label} label={x.label} value={fmt(x.v, x.k)} note={x.note} />)}</div> : <Empty text="No records match the current filters." />}
    <DimView rows={rows} p={p} title="Performance by Channel / Campaign Type" options={[['CampaignChannel'], ['CampaignType']]} />
    <Card title="Data availability notes"><ul className="list-disc pl-5 text-sm text-slate-600 space-y-1">{limitations(p).map(l => <li key={l}>{l}</li>)}</ul></Card></div>
}

export function Insights({ rows, p }: { rows: Row[]; p: Profile }) {
  const list = insights(rows, p)
  return <div className="space-y-3">
    <p className="text-sm text-slate-500">Generated by fixed rules applied to the filtered data (no AI model). Findings describe observed patterns, not causes.</p>
    {list.length ? list.map(i => <Card key={i.title} title={i.title}><div className="text-indigo-700 font-semibold">{i.metric}</div>
      <p className="text-sm text-slate-600 mt-1">{i.text}</p><p className="text-sm mt-1"><b>Possible action:</b> {i.rec}</p></Card>) : <Empty text="Not enough data under the current filters to generate insights." />}</div>
}
